-- ── Tabela de referência: chaves válidas de municípios (anti-cheat) ──
create table if not exists public.cities (
  key text primary key
);

alter table public.cities enable row level security;
create policy "cities são públicas" on public.cities for select using (true);

-- ── Perfis dos jogadores ──
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nickname text not null check (char_length(trim(nickname)) between 2 and 20),
  total_births integer not null default 0,
  created_at timestamptz not null default now()
);
create unique index if not exists profiles_nickname_unique on public.profiles (lower(trim(nickname)));

alter table public.profiles enable row level security;
create policy "perfis são públicos para leitura" on public.profiles for select using (true);
create policy "cria o próprio perfil" on public.profiles for insert with check (auth.uid() = id);
create policy "edita o próprio perfil" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

-- jogador só pode editar o apelido; contadores são do trigger
revoke update on public.profiles from authenticated;
grant update (nickname) on public.profiles to authenticated;

-- ── Nascimentos ──
create table if not exists public.births (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  city_key text not null references public.cities (key),
  born_at timestamptz not null default now(),
  unique (user_id, city_key)
);
create index if not exists births_user_recent on public.births (user_id, born_at desc);

alter table public.births enable row level security;
create policy "nascimentos são públicos para leitura" on public.births for select using (true);
create policy "registra o próprio nascimento" on public.births for insert with check (auth.uid() = user_id);

-- ── Contador global por cidade ──
create table if not exists public.city_counts (
  city_key text primary key references public.cities (key),
  births integer not null default 0
);

alter table public.city_counts enable row level security;
create policy "contadores são públicos" on public.city_counts for select using (true);

-- ── Trigger: rate-limit (espelha o cooldown do jogo) + contadores ──
create or replace function public.on_birth()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1 from public.births b
    where b.user_id = new.user_id
      and b.born_at > now() - interval '1.2 seconds'
  ) then
    raise exception 'rate_limited';
  end if;

  insert into public.city_counts (city_key, births)
  values (new.city_key, 1)
  on conflict (city_key) do update set births = public.city_counts.births + 1;

  update public.profiles set total_births = total_births + 1 where id = new.user_id;

  return new;
end
$$;

drop trigger if exists births_before_insert on public.births;
create trigger births_before_insert
  before insert on public.births
  for each row execute function public.on_birth();

